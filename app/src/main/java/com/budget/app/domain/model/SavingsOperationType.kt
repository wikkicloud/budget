package com.budget.app.domain.model

/** Тип операции по копилке. */
enum class SavingsOperationType {
    /** Пополнение с кошелька: баланс копилки растёт, кошелька — падает. */
    DEPOSIT,

    /** Возврат из копилки в кошелёк: баланс копилки падает, кошелька — растёт. */
    WITHDRAW,

    /** Начисление процентов: растёт только копилка, в аналитике считается доходом. */
    INTEREST
}